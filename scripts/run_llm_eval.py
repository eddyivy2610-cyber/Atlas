"""Run the real LLM evaluation pipeline for a target repo using raw source code extraction.

Protocol
--------
This script runs Phase 1:
  1. Reads all raw Python source files of the target package (zero AST pre-extraction).
  2. Formats a raw-code distillation prompt containing only the plain source files.
  3. Calls Gemini to extract the system architecture directly from raw code.
  4. Saves raw PlantUML output and parsed candidate IR (with zero verifier fields).
  5. Generates the blind labeling template with explicit mechanical rules for
     REQUIRED core classes vs INTERNAL_EXCLUDED helper classes.

Mechanical Labeling Rule
------------------------
  - REQUIRED (Expected in class diagram): Top-level public domain classes (not prefixed with '_'),
    exported in __all__ or documented as public interfaces. If omitted by the LLM, this counts
    as a False Negative (FN).
  - INTERNAL_EXCLUDED (Expected to be omitted): Private classes (prefixed with '_'), test harnesses,
    internal typing info dicts, or OS-specific compatibility wrappers. If omitted by the LLM,
    this counts as a True Negative (TN).
  - HALLUCINATED: Classes generated by the LLM that do not exist in the codebase source.
  - DRIFTED: Classes that exist in source but where the LLM generated inaccurate methods/parameters.
  - MATCH: Real classes where name, methods, and structure match source faithfully.

Usage
-----
    $env:GEMINI_API_KEY = "your-key"
    python scripts/run_llm_eval.py --repo tinydb
    python scripts/run_llm_eval.py --repo click
"""

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

# Project root on path
REPO_ROOT = Path(__file__).parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from google import genai
from google.genai import types as genai_types

from umldoc.extractors.static_ast import ASTStaticExtractor
from umldoc.parser.puml_parser import PlantUMLParser
from umldoc.readability.distiller import DiagramDistiller


# ---------------------------------------------------------------------------
# Repo registry: name → source directory path
# ---------------------------------------------------------------------------
REPO_REGISTRY = {
    "tinydb": REPO_ROOT / "data" / "repos" / "tinydb" / "tinydb",
    "click":  REPO_ROOT / ".venv" / "Lib" / "site-packages" / "click",
}


def _resolve_repo_path(name: str) -> Path:
    path = REPO_REGISTRY.get(name)
    if path and path.exists():
        return path
    raise SystemExit(f"[error] Unknown repo '{name}' or path not found: {path}")


# ---------------------------------------------------------------------------
# Phase 1 helpers
# ---------------------------------------------------------------------------

def _extract_ground_truth(repo_path: Path, repo_name: str):
    """Run AST extractor on the exact same directory provided to the LLM."""
    extractor = ASTStaticExtractor(project_name=repo_name, root_path=str(repo_path))
    model = extractor.extract_directory(target_dir=str(repo_path))
    print(f"  [extract] AST Ground Truth: {len(model.classes)} classes, {len(model.relations)} relations")
    return model


def _build_raw_source_prompt(repo_path: Path, repo_name: str) -> dict[str, str]:
    """Read all Python source files in repo_path and format raw-code prompt without any AST hints."""
    source_files = {}
    excludes = {"venv", ".venv", "__pycache__", ".git", "build", "dist", "site-packages"}
    for root, dirs, files in os.walk(repo_path):
        dirs[:] = [d for d in dirs if d not in excludes and not d.startswith(".")]
        for f in files:
            if f.endswith(".py"):
                fpath = Path(root) / f
                rel_name = fpath.relative_to(repo_path).as_posix()
                try:
                    source_files[rel_name] = fpath.read_text(encoding="utf-8", errors="replace")
                except Exception as e:
                    print(f"  [warn] Could not read {fpath}: {e}")

    total_chars = sum(len(v) for v in source_files.values())
    print(f"  [prompt] Packaged {len(source_files)} raw Python source files ({total_chars:,} chars) with 0 AST scaffolding")

    return DiagramDistiller.format_raw_code_prompt(
        source_files=source_files,
        project_name=repo_name,
        focus_area=f"Core domain architecture, classes, and interactions of {repo_name}",
        diagram_format="PlantUML",
    )


def _call_gemini(prompt: dict[str, str], api_key: str, model_name: str) -> str:
    """Call Gemini and return raw text output."""
    client = genai.Client(api_key=api_key)
    response = client.models.generate_content(
        model=model_name,
        contents=prompt["user_prompt"],
        config=genai_types.GenerateContentConfig(
            system_instruction=prompt["system_prompt"],
            temperature=0.2,
            max_output_tokens=16384,
        ),
    )
    return response.text


def _candidate_to_plain_dict(candidate) -> dict:
    """Convert parsed StaticModelIR to a plain dict with NO verifier fields."""
    return {
        "classes": [
            {
                "name": cls.name,
                "kind": cls.kind.value,
                "is_abstract": cls.is_abstract,
                "bases": cls.bases,
                "methods": [
                    {
                        "name": m.name,
                        "parameters": [p.name for p in m.parameters],
                        "return_type": m.return_type,
                    }
                    for m in cls.methods
                ],
                "attributes": [
                    {"name": a.name, "type": a.type_annotation}
                    for a in cls.attributes
                ],
            }
            for cls in candidate.classes
        ],
        "relations": [
            {
                "from": r.source_id,
                "to": r.target_id,
                "type": r.relation_type.value,
            }
            for r in candidate.relations
        ],
    }


def _build_blind_labels_template(
    candidate,
    ground_truth,
    repo_name: str,
    repo_path: Path,
    generated_at: str,
) -> dict:
    """Build the blind-labels template applying the documented mechanical rule."""
    gt_class_map = {c.name: c for c in ground_truth.classes}
    candidate_names = {c.name for c in candidate.classes}

    candidate_entries = []
    for cls in candidate.classes:
        gt_cls = gt_class_map.get(cls.name)
        if gt_cls and gt_cls.source_location:
            try:
                rel = Path(gt_cls.source_location.file_path).relative_to(repo_path)
                src_ref = f"{rel}:{gt_cls.source_location.start_line}"
            except ValueError:
                src_ref = f"{gt_cls.source_location.file_path}:{gt_cls.source_location.start_line}"
        elif gt_cls:
            src_ref = "IN_SOURCE_no_location"
        else:
            src_ref = "NOT_IN_SOURCE"

        candidate_entries.append({
            "name": cls.name,
            "llm_methods": [m.name for m in cls.methods],
            "source_ref": src_ref,
            "verdict": "__FILL_IN__",
            "_valid_verdicts": ["MATCH", "HALLUCINATED", "DRIFTED"],
            "_note": "MATCH = class & methods match source. DRIFTED = class exists but signatures/details wrong. HALLUCINATED = class does not exist in code.",
        })

    omitted_entries = []
    for gt_cls in ground_truth.classes:
        if gt_cls.name not in candidate_names:
            if gt_cls.source_location:
                try:
                    rel = Path(gt_cls.source_location.file_path).relative_to(repo_path)
                    src_ref = f"{rel}:{gt_cls.source_location.start_line}"
                except ValueError:
                    src_ref = f"{gt_cls.source_location.file_path}:{gt_cls.source_location.start_line}"
            else:
                src_ref = "IN_SOURCE_no_location"

            # Apply mechanical categorization:
            # - Private classes (starting with '_'), test helpers, InfoDicts -> INTERNAL_EXCLUDED (expected to be omitted -> TN)
            # - Public domain classes -> REQUIRED (omission is a coverage loss -> FN)
            is_private = gt_cls.name.startswith("_") or "InfoDict" in gt_cls.name or "testing" in src_ref or "compat" in src_ref or "winconsole" in src_ref
            category = "INTERNAL_EXCLUDED" if is_private else "REQUIRED"

            omitted_entries.append({
                "name": gt_cls.name,
                "source_ref": src_ref,
                "category": category,
                "verdict": category,  # REQUIRED (FN if omitted) or INTERNAL_EXCLUDED (TN if omitted)
            })

    return {
        "schema_version": "2.0",
        "repo": repo_name,
        "generated_at": generated_at,
        "mechanical_rule": (
            "1. REQUIRED: Public domain classes that belong in a high-level class diagram. If omitted by the LLM, this is evaluated as a False Negative (FN).\n"
            "2. INTERNAL_EXCLUDED: Private helpers (_*), OS wrappers, and internal typing dicts. If omitted by the LLM, this is evaluated as a True Negative (TN).\n"
            "3. CANDIDATES: MATCH (valid), DRIFTED (signature/structural divergence), or HALLUCINATED (invented symbol)."
        ),
        "candidate_classes": candidate_entries,
        "omitted_classes": omitted_entries,
    }


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="Run real LLM evaluation using raw source code extraction.")
    parser.add_argument(
        "--repo", required=True, choices=list(REPO_REGISTRY.keys()),
        help="Repo to evaluate (tinydb or click)"
    )
    parser.add_argument(
        "--model", default="gemini-3.6-flash",
        help="Gemini model name (default: gemini-3.6-flash)"
    )
    args = parser.parse_args()

    api_key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not api_key:
        sys.exit(
            "[error] No API key found. Set GEMINI_API_KEY or GOOGLE_API_KEY "
            "environment variable before running this script."
        )

    repo_name = args.repo
    repo_path = _resolve_repo_path(repo_name)
    out_dir = REPO_ROOT / "output"
    out_dir.mkdir(exist_ok=True)

    generated_at = datetime.now(timezone.utc).isoformat()

    print(f"\n[Phase 1] Raw-Source LLM Evaluation: {repo_name} ({repo_path})")
    print(f"  Model: {args.model}")
    print(f"  Timestamp: {generated_at}")
    print()

    # --- Step 1: Extract ground truth AST ---
    print("[1/5] Extracting ground truth AST ...")
    ground_truth = _extract_ground_truth(repo_path, repo_name)

    # --- Step 2: Build raw source prompt (Zero AST hints) ---
    print("[2/5] Building raw source code prompt ...")
    prompt = _build_raw_source_prompt(repo_path, repo_name)
    prompt_file = out_dir / f"{repo_name}_llm_prompt.txt"
    prompt_file.write_text(
        f"=== SYSTEM PROMPT ===\n{prompt['system_prompt']}\n\n"
        f"=== USER PROMPT ===\n{prompt['user_prompt']}",
        encoding="utf-8",
    )
    print(f"  Prompt saved to {prompt_file}")

    # --- Step 3: Call Gemini ---
    print(f"[3/5] Calling Gemini ({args.model}) with raw source text ...")
    raw_puml = _call_gemini(prompt, api_key, args.model)

    raw_file = out_dir / f"{repo_name}_llm_raw.puml"
    raw_file.write_text(raw_puml, encoding="utf-8")
    print(f"  Raw LLM output saved to {raw_file}")
    print(f"  Output length: {len(raw_puml):,} chars, {raw_puml.count(chr(10))} lines")

    # --- Step 4: Parse to candidate IR (NO verifier run) ---
    print("[4/5] Parsing LLM output to candidate IR ...")
    candidate = PlantUMLParser.parse_class_diagram(raw_puml, project_name=f"{repo_name}-LLM")
    print(f"  Parsed {len(candidate.classes)} classes, {len(candidate.relations)} relations")

    candidate_plain = _candidate_to_plain_dict(candidate)
    candidate_file = out_dir / f"{repo_name}_llm_candidate.json"
    candidate_file.write_text(
        json.dumps(
            {
                "_note": (
                    "This file contains ONLY what the LLM produced from raw Python source code. "
                    "No verifier output, no confidence scores. "
                ),
                "repo": repo_name,
                "model": args.model,
                "generated_at": generated_at,
                **candidate_plain,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"  Candidate-only JSON saved to {candidate_file}")

    # --- Step 5: Generate blind-labels template ---
    print("[5/5] Generating blind-labels template ...")
    template = _build_blind_labels_template(
        candidate, ground_truth, repo_name, repo_path, generated_at
    )
    template_file = out_dir / f"{repo_name}_llm_blind_labels_TEMPLATE.json"
    template_file.write_text(json.dumps(template, indent=2), encoding="utf-8")
    print(f"  Blind-labels template saved to {template_file}")

    print()
    print("=" * 62)
    print("  Phase 1 complete.")
    print()
    print("  NEXT STEPS:")
    print(f"  1. Read:  output/{repo_name}_llm_candidate.json")
    print(f"  2. Open:  output/{repo_name}_llm_blind_labels_TEMPLATE.json")
    print(f"  3. Fill verdicts in candidate_classes (MATCH | DRIFTED | HALLUCINATED)")
    print(f"  4. Save as: output/{repo_name}_llm_blind_labels.json")
    print(f"  5. Lock:    python scripts/lock_labels.py --repo {repo_name}")
    print(f"  6. Test:    python -m pytest tests/test_llm_real_eval.py -v -s -k {repo_name}")
    print("=" * 62)


if __name__ == "__main__":
    main()
