"""Real LLM evaluation test comparing blind human ground-truth labels against DiagramVerifier output.

Protocol verification:
1. Validates that the SHA-256 lock file exists and matches the blind labels file.
2. Loads raw PlantUML output generated by the LLM.
3. Parses the raw PlantUML into candidate StaticModelIR.
4. Runs DiagramVerifier on the codebase ground truth AST vs candidate.
5. Computes Precision, Recall, F1, and Hallucination Detection Rate against blind labels.
6. Asserts complete confusion matrix accounting (no silent drops).
"""

import hashlib
import json
from pathlib import Path
import pytest

from umldoc.extractors.static_ast import ASTStaticExtractor
from umldoc.ir.base import VerificationStatus
from umldoc.parser.puml_parser import PlantUMLParser
from umldoc.verifier.comparator import DiagramVerifier
from umldoc.verifier.metrics import MetricsCalculator

REPO_ROOT = Path(__file__).parents[1]
OUTPUT_DIR = REPO_ROOT / "output"

REPOS = {
    "tinydb": REPO_ROOT / "data" / "repos" / "tinydb" / "tinydb",
    "click": REPO_ROOT / ".venv" / "Lib" / "site-packages" / "click",
}


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


@pytest.mark.parametrize("repo_name", ["tinydb", "click"])
def test_real_llm_evaluation(repo_name: str):
    raw_puml_file = OUTPUT_DIR / f"{repo_name}_llm_raw.puml"
    labels_file = OUTPUT_DIR / f"{repo_name}_llm_blind_labels.json"
    lock_file = OUTPUT_DIR / f"{repo_name}_llm_blind_labels.lock"

    if not raw_puml_file.exists() or not labels_file.exists():
        pytest.skip(f"LLM output or blind labels not generated for {repo_name}. Run scripts/run_llm_eval.py first.")

    # 1. Verify hash lock integrity
    assert lock_file.exists(), (
        f"Lock file {lock_file.name} missing! You must run 'python scripts/lock_labels.py --repo {repo_name}' "
        "before running tests to seal blind labels."
    )
    lock_data = json.loads(lock_file.read_text(encoding="utf-8"))
    actual_hash = _sha256_file(labels_file)
    assert lock_data.get("sha256") == actual_hash, (
        f"Hash mismatch for {labels_file.name}! Expected {lock_data.get('sha256')}, got {actual_hash}. "
        "Labels must not be modified after locking."
    )

    # 2. Extract ground truth AST
    repo_path = REPOS[repo_name]
    extractor = ASTStaticExtractor(project_name=repo_name, root_path=str(repo_path))
    ground_truth = extractor.extract_directory(target_dir=str(repo_path))

    # 3. Parse raw LLM PlantUML
    raw_puml = raw_puml_file.read_text(encoding="utf-8")
    candidate_model = PlantUMLParser.parse_class_diagram(raw_puml, project_name=f"{repo_name}-LLM")

    # 4. Run verifier
    verifier = DiagramVerifier(ground_truth=ground_truth)
    summary = verifier.verify_candidate_model(candidate_model)

    # 5. Load blind labels
    blind_data = json.loads(labels_file.read_text(encoding="utf-8"))
    status_map = {
        "MATCH": VerificationStatus.MATCH,
        "REQUIRED": VerificationStatus.MATCH,
        "HALLUCINATED": VerificationStatus.HALLUCINATED,
        "DRIFTED": VerificationStatus.DRIFTED,
        "INTERNAL_EXCLUDED": VerificationStatus.MISSING,
        "OMITTED": VerificationStatus.MISSING,
    }

    expected_labels = {}
    for entry in blind_data.get("candidate_classes", []):
        name = entry["name"]
        verdict = entry["verdict"].strip().upper()
        if verdict in status_map:
            expected_labels[name] = status_map[verdict]

    for entry in blind_data.get("omitted_classes", []):
        name = entry["name"]
        verdict = entry["verdict"].strip().upper()
        if verdict in status_map:
            expected_labels[name] = status_map[verdict]

    # 6. Compute metrics
    metrics = MetricsCalculator.compute_metrics(summary, expected_labels)

    tp = metrics.true_positives
    fp = metrics.false_positives
    fn = metrics.false_negatives
    tn = metrics.true_negatives
    total_accounted = tp + fp + fn + tn
    total_expected = len(expected_labels) - metrics.skipped_labels

    print(f"\n========================================================")
    print(f"  REAL LLM EVALUATION REPORT: {repo_name.upper()}")
    print(f"========================================================")
    print(f"  Total Candidate Classes Generated: {len(candidate_model.classes)}")
    print(f"  Total Ground Truth Classes in Code: {len(ground_truth.classes)}")
    print(f"  Confusion Matrix: TP={tp} | FP={fp} | FN={fn} | TN={tn}")
    print(f"  Total Accounted: {total_accounted} (Expected: {total_expected})")
    print(f"  Skipped Labels: {metrics.skipped_labels}")
    print(f"  Unlabelled Verifier Records: {metrics.unlabelled_records}")
    print(f"  --------------------------------------------------------")
    print(f"  Precision:                    {metrics.precision:.4f}")
    print(f"  Recall:                       {metrics.recall:.4f}")
    print(f"  F1 Score:                     {metrics.f1_score:.4f}")
    print(f"  Hallucination Detection Rate: {metrics.hallucination_detection_rate:.4f}")
    print(f"========================================================")

    # Save metrics JSON
    metrics_out = OUTPUT_DIR / f"{repo_name}_llm_eval_metrics.json"
    metrics_out.write_text(
        json.dumps(
            {
                "repo": repo_name,
                "confusion_matrix": {"TP": tp, "FP": fp, "FN": fn, "TN": tn},
                "total_accounted": total_accounted,
                "skipped_labels": metrics.skipped_labels,
                "unlabelled_records": metrics.unlabelled_records,
                "metrics": {
                    "precision": metrics.precision,
                    "recall": metrics.recall,
                    "f1_score": metrics.f1_score,
                    "hallucination_detection_rate": metrics.hallucination_detection_rate,
                },
                "lock_hash": actual_hash,
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    # Invariants
    assert total_accounted == total_expected
    assert metrics.skipped_labels == 0
    assert 0.0 <= metrics.precision <= 1.0
    assert 0.0 <= metrics.recall <= 1.0
    assert 0.0 <= metrics.f1_score <= 1.0
    assert 0.0 <= metrics.hallucination_detection_rate <= 1.0
